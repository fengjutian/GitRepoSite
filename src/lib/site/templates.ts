import { escapeHtml } from '../content/markdown';
import type { GenerationLanguage, ProjectMetadata } from '../schema';

export interface NavItem {
  title: string;
  href: string;
  slug: string;
}

export interface RenderOptions {
  metadata: ProjectMetadata;
  language: GenerationLanguage;
  nav: NavItem[];
  siteTitle: string;
  siteDescription: string;
  canonicalPath: string;
}

const UI_TEXT = {
  'zh-CN': {
    docs: '文档',
    home: '首页',
    source: '源码仓库',
    license: '许可证',
    generatedBy: '本页面由 RepoSite 从原始仓库内容确定性生成。',
    onThisPage: '本页目录',
    backToTop: '返回顶部',
    search: '搜索',
  },
  'en-US': {
    docs: 'Documentation',
    home: 'Home',
    source: 'Source repository',
    license: 'License',
    generatedBy: 'This page was deterministically generated by RepoSite from the original repository content.',
    onThisPage: 'On this page',
    backToTop: 'Back to top',
    search: 'Search',
  },
} as const;

export function uiText(language: GenerationLanguage) {
  return UI_TEXT[language];
}

export function renderLayout(options: RenderOptions & { title: string; body: string; extraHead?: string }): string {
  const { metadata, language, nav, siteTitle, siteDescription, canonicalPath } = options;
  const text = uiText(language);
  const navHtml = nav
    .map(
      (item) =>
        `<li><a href="${escapeHtml(item.href)}" data-slug="${escapeHtml(item.slug)}">${escapeHtml(item.title)}</a></li>`,
    )
    .join('\n            ');

  return `<!doctype html>
<html lang="${escapeHtml(language)}">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${escapeHtml(options.title)}</title>
    <meta name="description" content="${escapeHtml(siteDescription)}" />
    <meta name="generator" content="RepoSite" />
    <meta name="robots" content="index, follow" />
    <meta property="og:type" content="website" />
    <meta property="og:title" content="${escapeHtml(options.title)}" />
    <meta property="og:description" content="${escapeHtml(siteDescription)}" />
    <meta property="og:url" content="${escapeHtml(metadata.repositoryUrl)}" />
    <link rel="canonical" href="${escapeHtml(canonicalPath)}" />
    <link rel="stylesheet" href="/assets/css/site.css" />
    ${options.extraHead ?? ''}
  </head>
  <body>
    <a class="skip-link" href="#main">${escapeHtml(text.backToTop)}</a>
    <header class="site-header">
      <div class="wrap header-inner">
        <a class="brand" href="/">${escapeHtml(siteTitle)}</a>
        <nav class="site-nav" aria-label="${escapeHtml(text.docs)}">
          <ul>
            <li><a href="/">${escapeHtml(text.home)}</a></li>
            <li><a href="/docs/">${escapeHtml(text.docs)}</a></li>
            <li><a href="${escapeHtml(metadata.repositoryUrl)}" rel="noopener noreferrer">${escapeHtml(text.source)}</a></li>
          </ul>
        </nav>
      </div>
    </header>
    <div class="wrap layout">
      <aside class="sidebar" aria-label="${escapeHtml(text.docs)}">
        <p class="sidebar-title">${escapeHtml(text.docs)}</p>
        <ul>
            ${navHtml}
        </ul>
      </aside>
      <main id="main" class="content">
${options.body}
      </main>
    </div>
    <footer class="site-footer">
      <div class="wrap">
        <p>${escapeHtml(text.generatedBy)}</p>
        <p>
          <a href="${escapeHtml(metadata.repositoryUrl)}" rel="noopener noreferrer">${escapeHtml(text.source)}</a>
          ${metadata.license?.identifier ? ` · ${escapeHtml(text.license)}: ${escapeHtml(metadata.license.identifier)}` : ''}
        </p>
        <p class="commit">commit ${escapeHtml(metadata.sourceCommitSha.slice(0, 12))}</p>
      </div>
    </footer>
    <script src="/assets/js/site.js" defer></script>
  </body>
</html>
`;
}

export function renderHome(options: {
  metadata: ProjectMetadata;
  language: GenerationLanguage;
  nav: NavItem[];
  siteTitle: string;
  siteDescription: string;
  canonicalPath: string;
  summary: string;
  highlights: string[];
  quickStart: string;
  tags: string[];
  audience?: string;
  sourceCommit: string;
}): string {
  const text = uiText(options.language);
  const highlights = options.highlights.length
    ? `<section class="section">
        <h2>${escapeHtml(options.language === 'zh-CN' ? '核心能力' : 'Highlights')}</h2>
        <ul class="highlights">
${options.highlights.map((item) => `          <li>${escapeHtml(item)}</li>`).join('\n')}
        </ul>
      </section>`
    : '';

  const quickStart = options.quickStart
    ? `<section class="section">
        <h2>${escapeHtml(options.language === 'zh-CN' ? '快速开始' : 'Quick start')}</h2>
        <pre class="quick-start"><code>${escapeHtml(options.quickStart)}</code></pre>
      </section>`
    : '';

  const tags = options.tags.length
    ? `<ul class="tags">${options.tags.map((tag) => `<li>${escapeHtml(tag)}</li>`).join('')}</ul>`
    : '';

  const body = `        <article class="prose">
          <h1>${escapeHtml(options.metadata.name)}</h1>
          <p class="lead">${escapeHtml(options.metadata.description)}</p>
          ${tags}
          <section class="section">
            <h2>${escapeHtml(options.language === 'zh-CN' ? '项目简介' : 'Overview')}</h2>
            <p>${escapeHtml(options.summary)}</p>
            ${options.audience ? `<p class="muted">${escapeHtml(options.audience)}</p>` : ''}
          </section>
          ${highlights}
          ${quickStart}
          <section class="section">
            <h2>${escapeHtml(text.docs)}</h2>
            <ul class="doc-list">
${options.nav
  .map((item) => `              <li><a href="${escapeHtml(item.href)}">${escapeHtml(item.title)}</a></li>`)
  .join('\n')}
            </ul>
          </section>
        </article>`;

  return renderLayout({
    ...options,
    title: options.siteTitle,
    body,
  });
}

export function renderDocument(options: {
  metadata: ProjectMetadata;
  language: GenerationLanguage;
  nav: NavItem[];
  siteTitle: string;
  siteDescription: string;
  canonicalPath: string;
  title: string;
  html: string;
  headings: Array<{ id: string; text: string; depth: number }>;
  sourcePath?: string;
  origin: string;
}): string {
  const text = uiText(options.language);
  const toc = options.headings.filter((heading) => heading.depth >= 2 && heading.depth <= 3);
  const tocHtml = toc.length
    ? `<nav class="toc" aria-label="${escapeHtml(text.onThisPage)}">
            <p class="toc-title">${escapeHtml(text.onThisPage)}</p>
            <ul>
${toc
  .map(
    (heading) =>
      `              <li class="toc-depth-${heading.depth}"><a href="#${escapeHtml(heading.id)}">${escapeHtml(heading.text)}</a></li>`,
  )
  .join('\n')}
            </ul>
          </nav>`
    : '';

  const sourceNote = options.sourcePath
    ? `<p class="source-note">${escapeHtml(text.source)}: <code>${escapeHtml(options.sourcePath)}</code></p>`
    : '';

  const body = `        <article class="prose">
          <h1>${escapeHtml(options.title)}</h1>
          ${sourceNote}
          ${tocHtml}
${options.html}
        </article>`;

  return renderLayout({
    ...options,
    title: `${options.title} · ${options.siteTitle}`,
    body,
  });
}

export function renderDocIndex(options: {
  metadata: ProjectMetadata;
  language: GenerationLanguage;
  nav: NavItem[];
  siteTitle: string;
  siteDescription: string;
  canonicalPath: string;
  items: Array<{ title: string; href: string; summary: string; sourcePath?: string }>;
}): string {
  const body = `        <article class="prose">
          <h1>${escapeHtml(options.language === 'zh-CN' ? '文档' : 'Documentation')}</h1>
          <ul class="doc-list">
${options.items
  .map(
    (item) => `            <li>
              <a href="${escapeHtml(item.href)}">${escapeHtml(item.title)}</a>
              ${item.summary ? `<p class="muted">${escapeHtml(item.summary)}</p>` : ''}
            </li>`,
  )
  .join('\n')}
          </ul>
        </article>`;

  return renderLayout({
    ...options,
    title: `${options.language === 'zh-CN' ? '文档' : 'Documentation'} · ${options.siteTitle}`,
    body,
  });
}

export function renderNotFound(options: {
  metadata: ProjectMetadata;
  language: GenerationLanguage;
  nav: NavItem[];
  siteTitle: string;
  siteDescription: string;
  canonicalPath: string;
}): string {
  const body = `        <article class="prose">
          <h1>404</h1>
          <p>${escapeHtml(options.language === 'zh-CN' ? '页面不存在。' : 'This page does not exist.')}</p>
          <p><a href="/">${escapeHtml(uiText(options.language).home)}</a></p>
        </article>`;
  return renderLayout({ ...options, title: `404 · ${options.siteTitle}`, body });
}

